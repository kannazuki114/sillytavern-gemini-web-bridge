import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const pkg = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));
const manifestPath = new URL('manifest.json', root);
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const source = readFileSync(new URL('web/extension.js', root), 'utf8');
const template = readFileSync(new URL('settings.html', root), 'utf8');
const js = source.replace('/*__GWB_VERSION__*/""', () => JSON.stringify(pkg.version)).replace('/*__GWB_TEMPLATE__*/""', () => JSON.stringify(template));
if (js.includes('/*__GWB_')) throw new Error('前端构建仍存在未替换占位符');
new Function(js);
writeFileSync(new URL('index.js', root), '/*! Gemini Web Bridge: generated by tools/build-extension.mjs */\n' + js);
if (manifest.version !== pkg.version) writeFileSync(manifestPath, JSON.stringify({ ...manifest, version: pkg.version }, null, 2) + '\n');
console.log('前端扩展已构建: manifest.json -> index.js, v' + pkg.version);
